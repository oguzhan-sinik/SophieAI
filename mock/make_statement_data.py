"""Write mock/src/statement-data.js from the bank's test customers.

    python3 mock/make_statement_data.py "<case folder>/test-environment/test-customers.json"

The file holds every answer of every statement service for every test customer, exactly as the
bank's file gives it. The Worker looks the answer up and returns it with its status code."""
import json
import sys
from pathlib import Path

source = json.loads(Path(sys.argv[1]).read_text(encoding='utf-8'))
customers = {str(c['customerNo']): c['services'] for c in source['customers']}
out = Path(__file__).parent / 'src' / 'statement-data.js'
out.write_text('// Generated by make_statement_data.py from the bank\'s test-customers.json. Do not edit.\nexport default '
               + json.dumps(customers, ensure_ascii=False, separators=(',', ':')).replace('\u2028', '\\u2028').replace('\u2029', '\\u2029') + ';\n', encoding='utf-8')
print(f'{len(customers)} customers, {out.stat().st_size} bytes -> {out}')
